const {chromium,expect}=require('@playwright/test');
const fs=require('fs'),path=require('path');
(async()=>{
 const out=path.resolve(process.env.EVIDENCE_DIR || path.join(__dirname,'../evidence/presentation-v2'));
 fs.mkdirSync(out,{recursive:true});
 const browser=await chromium.launch();
 const page=await browser.newPage({viewport:{width:1440,height:1080}});
 const errors=[];let inferenceRequests=0;
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('request',r=>{if(r.url().endsWith('/api/analyze')&&r.method()==='POST')inferenceRequests++;});
 const exportDecision=async(name)=>{const event=page.waitForEvent('download');await page.getByRole('button',{name:'Export JSON'}).click();await(await event).saveAs(path.join(out,name));return JSON.parse(fs.readFileSync(path.join(out,name)));};
 try{
  await page.goto(process.env.BASE_URL || 'http://127.0.0.1:8765/');
  await expect(page.getByRole('button',{name:'Analyze ticket'})).toBeEnabled({timeout:120000});
  await expect(page.locator('#sample')).toHaveValue('invoice');
  await page.getByRole('button',{name:'Analyze ticket'}).click();
  await expect(page.locator('#result')).toBeVisible({timeout:60000});
  const initial=await exportDecision('initial-result.json');
  expect(Object.keys(initial.answers)).toHaveLength(4);
  expect(initial.device).toBe(process.env.EXPECT_DEVICE || 'mps');
  const before=inferenceRequests;
  await page.locator('#policy-preset').selectOption('exploratory');
  await expect(page.locator('#policy-update')).toContainText('no new Laya inference');
  await page.locator('#threshold').fill('0');
  await expect(page.locator('#confidence')).toContainText('threshold 0.0%');
  await expect(page.locator('#routing-state')).toContainText('Eligible for automatic routing');
  const recalculated=await exportDecision('recalculated-result.json');
  expect(recalculated.inference_id).toBe(initial.inference_id);
  expect(recalculated.answers).toEqual(initial.answers);
  expect(recalculated.inference_ms).toBe(initial.inference_ms);
  expect(inferenceRequests).toBe(before);
  await page.locator('#policy-preset').selectOption('exploratory');
  await expect(page.locator('#confidence')).toContainText('threshold 20.0%');
  await page.screenshot({path:path.join(out,'live-desktop.png'),fullPage:true});
  await page.locator('#policy-preset').selectOption('conservative');
  await expect(page.locator('#confidence')).toContainText('threshold 80.0%');
  await page.getByRole('button',{name:'Presenter guide'}).click();
  await expect(page.getByText('What this demo demonstrates')).toBeVisible();
  await page.getByRole('button',{name:'Load refund example'}).click();
  await expect(page.locator('#sample')).toHaveValue('duplicate');
  await expect(page.locator('#result')).toBeHidden();
  await page.getByRole('button',{name:'Analyze ticket'}).click();
  await expect(page.locator('#result')).toBeVisible({timeout:60000});
  const refund=await exportDecision('refund-result.json');
  if(['refund','cancellation'].includes(refund.answers.requested_action.choice))await expect(page.locator('#approval-state')).toContainText('Human approval required');
  await page.getByRole('button',{name:'Decision schema'}).click();
  await expect(page.locator('#schema-code')).toContainText('requested_action');
  await page.getByRole('button',{name:'Evaluate samples'}).click();
  await page.getByRole('button',{name:'Run 16 samples'}).click();
  await expect(page.locator('#evaluation-progress')).toContainText('Completed 16 / 16',{timeout:240000});
  await expect(page.locator('#evaluation-progress')).toContainText('0 failures');
  await expect(page.locator('#evaluation-rows tr')).toHaveCount(16);
  await expect(page.locator('#comparison-rows tr')).toHaveCount(3);
  await page.screenshot({path:path.join(out,'evaluation-desktop.png'),fullPage:true});
  const event=page.waitForEvent('download');await page.getByRole('button',{name:'Export evaluation'}).click();await(await event).saveAs(path.join(out,'evaluation.json'));
  const evaluation=JSON.parse(fs.readFileSync(path.join(out,'evaluation.json')));
  await expect(page.locator('.action-result.fail')).toHaveCount(evaluation.rows.filter(r=>r.result.answers.requested_action.choice!==r.expected.requested_action).length);
  expect(evaluation.rows.every(r=>!r.result.usage.truncated && r.result.cpu_fallback_count===0)).toBe(true);
  for(const [name,summary] of Object.entries(evaluation.policy_comparison)){
   const eligible=evaluation.rows.filter(r=>r.result.policy_comparison[name].routing.status==='auto_route_candidate');
   expect(summary.eligible).toBe(eligible.length);
   expect(summary.wrong_auto_routes).toBe(eligible.filter(r=>r.result.answers.department.choice!==r.expected.department).length);
  }
  await page.getByRole('button',{name:'Live demo'}).click();
  await page.locator('#sample').selectOption('pt-invoice');
  await expect(page.locator('#model')).toHaveValue('multilingual');
  await page.getByRole('button',{name:'Analyze ticket'}).click();
  await expect(page.locator('#result')).toBeVisible({timeout:60000});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(out,'live-mobile.png'),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Presenter guide'}).click();
  await page.screenshot({path:path.join(out,'guide-mobile.png'),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Live demo'}).click();
  await page.locator('#ticket').fill('');await expect(page.locator('#result')).toBeHidden();
  await expect(page.getByRole('button',{name:'Analyze ticket'})).toBeDisabled();
  expect(errors).toEqual([]);
  fs.writeFileSync(path.join(out,'browser-check.json'),JSON.stringify({passed:true,realInference:true,inferenceRequests,policyRecalculationUsesNoInference:true,viewports:[1440,390],checks:['four real signals','unchanged inference ID and answers after policy edits','routing/approval separation','guide example links','JSON export','16 real samples','policy metrics recomputed independently','Portuguese','mobile overflow','stale result invalidation'],errors},null,2));
  console.log(JSON.stringify({metrics:evaluation.metrics,policies:evaluation.policy_comparison}));
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
